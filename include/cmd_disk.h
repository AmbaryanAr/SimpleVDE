#ifndef CMD_DISK_H
#define CMD_DISK_H

/**
 * @file cmd_disk.h
 * @brief Заголовочный файл команд для работы с диском.
 *
 * Содержит объявления функций, реализующих команды работы с диском:
 * создание образа диска, вывод информации, чтение секторов.
 */

#include "cmd.h"
#include "fat32.h"
#include "error_codes.h"

/**
 * @brief Создаёт новый файл образа диска.
 *
 * Обрабатывает команду `--disk-create`.
 * Параметры извлекаются из структуры `args`:
 * - file: путь к создаваемому файлу.
 * - table: тип таблицы разделов ("mbr" или "gpt").
 * - size: размер диска в байтах (поддерживаются суффиксы K/M/G).
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения.
 */
ErrorCode cmd_disk_create(CMDArgs *args);

/**
 * @brief Выводит информацию о диске и его таблице разделов.
 *
 * Обрабатывает команду `--disk-info`.
 * Параметры:
 * - file: путь к файлу образа диска.
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения.
 */
ErrorCode cmd_disk_info(CMDArgs *args);

/**
 * @brief Читает указанное количество байт с диска по заданному смещению и выводит в hex-дампе.
 *
 * Обрабатывает команду `--disk-read`.
 * Параметры:
 * - file: путь к файлу образа диска.
 * - offset: смещение от начала диска в байтах.
 * - count: количество байт для чтения.
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения.
 */
ErrorCode cmd_disk_read(CMDArgs *args);

/**
 * @brief Читает указанное количество секторов с диска и выводит их в hex-дампе.
 * 
 * Обрабатывает команду `--disk-read-s`.
 * Параметры извлекаются из структуры `args`:
 * - file: путь к файлу образа диска.
 * - offset: смещение от начала диска в секторах.
 * - count: количество секторов для чтения.
 * 
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения.
 */
ErrorCode cmd_disk_read_s(CMDArgs *args);

/**
 * @brief Записывает загрузочный код в MBR (первые 446 байт) из файла.
 * @param args Аргументы командной строки (ожидается file, src).
 * @return ErrorCode.
 */
ErrorCode cmd_mbr_write(CMDArgs *args);

/**
 * @brief Записывает загрузочный код в BPB-сектор (сектор 0), начиная со смещения 90 байт.
 * @param args Аргументы командной строки (ожидается file, src).
 * @return ErrorCode.
 */
ErrorCode cmd_bpb_write(CMDArgs *args);

#endif // CMD_DISK_H
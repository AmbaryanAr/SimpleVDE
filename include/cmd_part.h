#ifndef CMD_PART_H
#define CMD_PART_H

#include "error_codes.h"
#include "cmd.h"

/**
 * @file cmd_part.h
 * @brief Заголовочный файл команд для управления разделами.
 */

/**
 * @brief Создаёт новый раздел на указанном диске.
 *
 * Обрабатывает команду `--part-create`.
 * Параметры извлекаются из структуры `args`:
 * - file: путь к файлу образа диска.
 * - part: номер раздела (начиная с 1).
 * - size: размер раздела в байтах (поддерживаются суффиксы K/M/G).
 * - type: тип раздела (например, "linux", "0x83" или GUID для GPT).
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения.
 */
ErrorCode cmd_part_create(CMDArgs *args);

/**
 * @brief Удаляет раздел с указанным номером.
 *
 * Обрабатывает команду `--part-delete`.
 * Параметры:
 * - file: путь к файлу образа диска.
 * - part: номер раздела (начиная с 1).
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения.
 */
ErrorCode cmd_part_delete(CMDArgs *args);

/**
 * @brief Изменяет тип указанного раздела.
 *
 * Обрабатывает команду `--part-set-type`.
 * Параметры:
 * - file: путь к файлу образа диска.
 * - part: номер раздела (начиная с 1).
 * - type: новый тип раздела (строка или hex-код для MBR, GUID для GPT).
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения.
 */
ErrorCode cmd_part_set_type(CMDArgs *args);

/**
 * @brief Устанавливает активный флаг для раздела (только для MBR).
 *
 * Обрабатывает команду `--part-set-active`.
 * Параметры:
 * - file: путь к файлу образа диска.
 * - part: номер раздела (начиная с 1).
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения (для GPT вернёт ERR_NOT_SUPPORTED).
 */
ErrorCode cmd_part_set_active(CMDArgs *args);

/**
 * @brief Снимает активный флаг с раздела (только для MBR).
 *
 * Обрабатывает команду `--part-set-inactive`.
 * Параметры:
 * - file: путь к файлу образа диска.
 * - part: номер раздела (начиная с 1).
 *
 * @param args Указатель на структуру с распарсенными аргументами командной строки.
 * @return ErrorCode – код результата выполнения (для GPT вернёт ERR_NOT_SUPPORTED).
 */
ErrorCode cmd_part_set_inactive(CMDArgs *args);

#endif // CMD_PART_H